/**
 * Hardcoded {@code plate_}/{@code crystal_}/{@code gem_}/{@code waste_}/{@code fragment_} resource
 * items ported from CE's {@code ModItems.java} (docs/phase1/moditems_generative.md section 3). CE
 * hand-wrote each of these as its own field rather than generating them from
 * {@code Mats}/{@code MaterialShapes} - the material sets between the ingot/nugget/billet/powder/
 * plate/crystal families are mismatched enough (see the research report) that a generation loop
 * would either miss items CE has or invent items CE does not, so this file mirrors CE's own
 * approach: one explicit registration per field, with a thin {@link #register(String)}/
 * {@link #registerParts(String)} helper only to remove the {@code new Item(new Item.Properties())}
 * boilerplate for the plain majority.
 *
 * <p>Deliberately excluded from this file, left to other Phase 1 areas:
 * <ul>
 *     <li>{@code plate_cast}/{@code plate_welded} - {@code ItemAutogen}-backed
 *     (moditems_generative.md section 1), already generated by {@link MaterialItemGenerator}.</li>
 *     <li>{@code plate_fuel_u233}/{@code u235}/{@code mox}/{@code pu239}/{@code sa326}/
 *     {@code ra226be}/{@code pu238be} (7 fields) - CE backs these with
 *     {@code ItemPlateFuel extends ItemFuelRod}, a stateful research-reactor fuel item
 *     (durability-encoded "life" counter, reactivity math) with zero relation to the plain
 *     {@code plate_} resource family beyond sharing a name prefix.
 *     {@code com.hbm.items.machine.ItemFuelRod}/{@code ItemPlateFuel} are explicitly claimed by the
 *     items_machine Phase 1 area (docs/phase1/items_machine.md, "port now" table, lines 44/55);
 *     registering {@code plate_fuel_*} here would duplicate that area's registration once it lands
 *     its own item classes, so those 7 ids are deliberately left out of this file.</li>
 * </ul>
 *
 * <p>CE backs most of the plain-flavor entries here with {@code ItemCustomLore}/
 * {@code ItemBakedBase} (automatic lore-tooltip-from-lang-key lookup, no gameplay effect on any
 * item in this file) or {@code ItemDrop} (drop-triggered effects), all from
 * {@code com.hbm.items.special} - a different concurrent Phase 1 area's package
 * (docs/phase1/items_special.md). As of this writing those two classes are not yet landed there,
 * so the items they would back still register as a plain {@link Item}; swapping the factory lambda
 * to the real special-item class is a one-line change per field once that area lands its base
 * classes, and changes no registry id, hazard binding, or creative-tab placement.
 * {@code com.hbm.items.special.ItemFuel} has since landed, so {@code crystal_coal} below is wired
 * to it directly instead of waiting.
 *
 * <p>{@code plate_armor_titanium}/{@code plate_armor_ajr}/{@code plate_armor_hev}/
 * {@code plate_armor_lunar}/{@code plate_armor_fau}/{@code plate_armor_dnt} are registered in this
 * file. This was cross-checked against the rest of the Phase 1 research wave rather than left as a
 * unilateral call: {@code docs/phase1/DIGEST_REMAINDER.md} (line 73) confirms the entire armor
 * system - {@code ModArmor}, every {@code Armor*}/{@code Jetpack*} class, and by extension anything
 * that consumes these plates as a crafting component - is deferred whole to Phase 3, blocked on
 * NeoForge's {@code Equippable}/data-component armor system. No Phase 1 area (this research wave's
 * 12 reports) claims or registers {@code plate_armor_*}, so there is no live ownership conflict
 * today; these six ids stay here as plain resource items, matching CE's own {@code ItemBase}
 * backing, until the Phase 3 armor area needs them as crafting inputs.</p>
 */
