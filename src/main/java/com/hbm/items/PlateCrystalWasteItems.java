    /**
     * No-op body - exists purely so {@link ModItems#register} has an explicit call that forces this
     * class to run its static initializers (and therefore register every field below) before
     * {@code ModItems.ITEMS.register(modEventBus)} fires, exactly like {@link MaterialItemGenerator}.
     */
    public static void registerAll() {
    }

    private static DeferredItem<Item> register(String name) {
        return register(name, new Item.Properties());
    }

    private static DeferredItem<Item> register(String name, Item.Properties properties) {
        return ModItems.ITEMS.register(name, () -> new Item(properties));
    }

    private static DeferredItem<Item> registerParts(String name) {
        return registerParts(name, new Item.Properties());
    }

    private static DeferredItem<Item> registerParts(String name, Item.Properties properties) {
        DeferredItem<Item> item = register(name, properties);
        CreativeTabContents.add(ModCreativeTabs.PARTS, item);
        return item;
    }

