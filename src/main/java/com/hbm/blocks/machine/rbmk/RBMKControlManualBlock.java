package com.hbm.blocks.machine.rbmk;

import com.hbm.blockentity.ITickableBE;
import com.hbm.blockentity.machine.rbmk.RBMKBlockEntities;
import com.hbm.blockentity.machine.rbmk.RBMKControlManualBlockEntity;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityTicker;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;
import org.jetbrains.annotations.Nullable;

/** Operator-facing manual control rod column. Ported from CE's {@code RBMKControl} block class. */
public class RBMKControlManualBlock extends RBMKControlBlock {

    public RBMKControlManualBlock(Properties properties, boolean moderated, boolean reasimPowered) {
        super(properties, moderated, reasimPowered);
    }

    @Nullable
    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return state.getValue(META) >= 12 ? new RBMKControlManualBlockEntity(RBMKBlockEntities.CONTROL_MANUAL.get(), pos, state) : null;
    }

    @Nullable
    @Override
    public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level, BlockState state, BlockEntityType<T> type) {
        return type == RBMKBlockEntities.CONTROL_MANUAL.get() ? ITickableBE.ticker() : null;
    }
}
